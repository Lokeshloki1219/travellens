-- V1__initial_schema.sql
--
-- TravelLens baseline schema, managed by Flyway.
--
-- Through Milestone 3 these tables were created implicitly by Hibernate with
-- spring.jpa.hibernate.ddl-auto=update, which meant the schema existed only as
-- a side effect of starting the application and was never reviewable or
-- repeatable. This migration makes the schema an explicit, version-controlled
-- artifact. The application now runs with ddl-auto=validate: Hibernate checks
-- that the entities match what Flyway built and refuses to start if they drift.
--
-- Column types reproduce exactly what Hibernate generated for these entities,
-- so an existing database and a freshly migrated one are identical.

-- ---------------------------------------------------------------- destination
CREATE TABLE destination (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    best_time_to_visit      varchar(255),
    budget_estimate         varchar(255),
    category                varchar(255),
    description             varchar(2000),
    image_url               varchar(255),
    must_visit_attractions  varchar(2000),
    name                    varchar(255),
    recommended_duration    varchar(255),
    things_to_avoid         varchar(2000),
    tips                    varchar(2000),
    PRIMARY KEY (id)
);

-- -------------------------------------------------------------------- app_user
-- "user" is reserved in PostgreSQL, hence app_user.
CREATE TABLE app_user (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    email     varchar(255) NOT NULL,
    name      varchar(255) NOT NULL,
    password  varchar(255) NOT NULL,
    role      varchar(255) CHECK (role IN ('USER', 'ADVISOR')),
    PRIMARY KEY (id),
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

-- --------------------------------------------------------------------- advisor
CREATE TABLE advisor (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    bio                  varchar(1000),
    name                 varchar(255),
    years_of_experience  integer,
    destination_id       bigint,
    PRIMARY KEY (id),
    CONSTRAINT fk_advisor_destination
        FOREIGN KEY (destination_id) REFERENCES destination (id)
);

-- -------------------------------------------------------- advisor_availability
-- The unique constraint on (advisor_id, slot_date, start_time) is the
-- database-level half of the double-booking guard; the booking endpoint
-- performs the same check inside a transaction.
CREATE TABLE advisor_availability (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    booked      boolean NOT NULL,
    slot_date   date,
    start_time  time(0) WITHOUT TIME ZONE,
    end_time    time(0) WITHOUT TIME ZONE,
    advisor_id  bigint,
    PRIMARY KEY (id),
    CONSTRAINT uk_availability_slot UNIQUE (advisor_id, slot_date, start_time),
    CONSTRAINT fk_availability_advisor
        FOREIGN KEY (advisor_id) REFERENCES advisor (id)
);

-- --------------------------------------------------------------------- booking
-- One booking per availability slot: the unique constraint on availability_id
-- is what actually makes a second concurrent booking fail.
CREATE TABLE booking (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    booked_at        timestamp(6) WITHOUT TIME ZONE,
    status           varchar(255) CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    advisor_id       bigint,
    availability_id  bigint,
    user_id          bigint,
    PRIMARY KEY (id),
    CONSTRAINT uk_booking_availability UNIQUE (availability_id),
    CONSTRAINT fk_booking_advisor
        FOREIGN KEY (advisor_id) REFERENCES advisor (id),
    CONSTRAINT fk_booking_availability
        FOREIGN KEY (availability_id) REFERENCES advisor_availability (id),
    CONSTRAINT fk_booking_user
        FOREIGN KEY (user_id) REFERENCES app_user (id)
);

-- --------------------------------------------------------------- traveler_post
-- media_url holds an application path of the form /uploads/<object-name>.
-- From Milestone 4 onward the bytes behind that path live in a Cloud Storage
-- bucket rather than on the container filesystem; the column format is
-- unchanged, so rows written before and after the move are interchangeable.
CREATE TABLE traveler_post (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    approximate_expense  double precision,
    caption              varchar(1000),
    created_at           timestamp(6) WITHOUT TIME ZONE,
    media_type           varchar(255),
    media_url            varchar(255),
    rating               integer,
    tip                  varchar(1000),
    destination_id       bigint,
    user_id              bigint,
    PRIMARY KEY (id),
    CONSTRAINT fk_post_destination
        FOREIGN KEY (destination_id) REFERENCES destination (id),
    CONSTRAINT fk_post_user
        FOREIGN KEY (user_id) REFERENCES app_user (id)
);

-- Indexes on the foreign keys the feed and booking screens filter by.
CREATE INDEX idx_post_destination   ON traveler_post (destination_id);
CREATE INDEX idx_post_created_at    ON traveler_post (created_at DESC);
CREATE INDEX idx_booking_user       ON booking (user_id);
CREATE INDEX idx_availability_advisor ON advisor_availability (advisor_id);
